#!/usr/bin/env bash
# make_test.sh : derive test_gemm_sm100.cu from llm/gemm/test_gemm.cu (same cases: S and M shapes, fp32 reference, cuBLAS compare/timing,
# persistent-vs-grid bit-exactness, RES aliasing).  UNTESTED on B200.  The only changes: Args -> tg::Args, gemm_tile -> tg::tile, smem size from the
# backend, and tg::prepare() (TMA descriptors) after the operand pointers are set.
set -e
cd "$(dirname "$0")"
python3 - <<'PY'
import re
s = open("../../gemm/test_gemm.cu").read()
s = s.replace('#include "gemm.cuh"', '#include "gemm_backend.cuh"')
s = re.sub(r'\bArgs\b', 'tg::Args', s)
s = s.replace('gemm_tile<L, E>(p,', 'tg::tile<L, E>(p,')
s = s.replace('constexpr int SM = smem_bytes();', 'constexpr int SM = tg::smem_bytes();')
s = s.replace('nsm, smem_bytes());', 'nsm, tg::smem_bytes());')
s = s.replace('p.A = A; p.B = B; p.C = C; p.aux = aux;', 'p.A = A; p.B = B; p.C = C; p.aux = aux; tg::prepare(p, L);')
assert s.count('tg::prepare') == 1 and 'tg::tile<L, E>' in s and s.count('tg::smem_bytes') == 2
s = "// GENERATED by make_test.sh from llm/gemm/test_gemm.cu -- UNTESTED on B200. Build: see README.md.\n" + s
open("test_gemm_sm100.cu", "w").write(s)
print("wrote test_gemm_sm100.cu")
PY
